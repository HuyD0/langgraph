-- How each lesson is going, over all time: one row per lesson in the running course, zeros for lessons nobody opened.
-- Counts add up across lessons; the rate columns are per lesson (add the counts and divide to combine).
CREATE OR REPLACE VIEW `{insights_catalog}`.drill_insights.lesson_summary (
  lesson_id COMMENT 'Short code of the lesson. Links to learner_lessons.lesson_id.',
  lesson COMMENT 'Lesson number and title together. Use this to name a lesson.',
  lesson_number COMMENT 'The number learners see, like 2.11 or P3.4. Text, so sort by position.',
  phase COMMENT 'Stage of the course: Frame, Design, Build and trace, Evaluate, Ship, Monitor or Platform track.',
  phase_order COMMENT 'Order of the phase, 1 for Frame. Sort phases by this.',
  module COMMENT 'Title of the small group of lessons on one topic inside a phase.',
  course_part COMMENT 'Main path or Platform track. Report them separately.',
  position COMMENT 'Place of the lesson in the course. Sort lessons by this.',
  learners_opened COMMENT 'Learners who opened the lesson, including those who only peeked at Learn or had it opened as their next lesson.',
  learners_past_learn COMMENT 'Learners who reached Check or further (or finished). The fair base for most rates.',
  learners_reached_build COMMENT 'Learners who reached Build (Practice on question lessons) or further.',
  learners_reached_explain COMMENT 'Learners who reached Explain or finished.',
  learners_finished COMMENT 'Learners who finished the lesson.',
  learners_in_progress COMMENT 'Learners past Learn who have not finished and are not stalled: working on it now, or with no recorded action to date it by.',
  learners_stalled COMMENT 'Learners past Learn who have not finished and whose last action on it is 7 or more days old.',
  learners_stuck COMMENT 'Learners stuck on it right now: stalled, needed help, last action 7 to 30 days old, not moved on.',
  learners_left_after_struggling COMMENT 'Learners who struggled, left it unfinished and moved on or went quiet for more than 30 days.',
  finish_rate COMMENT 'Of the learners who have settled (finished, or stalled), the share who finished: finished divided by finished plus stalled, from 0 to 1. People working on it now are left out. To combine lessons add the counts and divide; never average this column.',
  first_check_answers COMMENT 'Learners who answered Check question 1.',
  first_check_wrong COMMENT 'Of those, how many picked a wrong option first.',
  first_check_wrong_rate COMMENT 'first_check_wrong divided by first_check_answers, 0 to 1. Per lesson only.',
  check_questions_tried COMMENT 'Check questions tried, all learners and all questions of the lesson, including ones not right yet.',
  check_questions_on_own COMMENT 'Of those, right on the first pick without a clue.',
  check_answers_shown COMMENT 'Check questions where a learner asked to see the answer.',
  check_on_own_rate COMMENT 'check_questions_on_own divided by check_questions_tried, 0 to 1. Low means the Learn step or the questions need work.',
  practice_learners COMMENT 'Learners who finished the practice questions inside this lesson (question lessons only).',
  practice_right_rate COMMENT 'Practice questions right first time divided by practice questions, from each learner latest run, 0 to 1. Empty for code lessons.',
  code_solvers COMMENT 'Learners who passed this lesson as a code exercise.',
  code_two_plus_hints_rate COMMENT 'Share of code solvers who needed hint step 2 or more, 0 to 1. Step 1 can be just Show the pattern.',
  explain_completions COMMENT 'Learners who filled every Explain gap.',
  explain_wrong_picks_per_learner COMMENT 'Average wrong word picks per learner who filled every Explain gap. High means the sentence or its word choices confuse people.',
  tutor_requests COMMENT 'Requests to the AI tutor about this lesson.',
  typed_questions COMMENT 'Questions learners wrote to the tutor about this lesson.',
  still_stuck_presses COMMENT 'Times learners pressed Still stuck after a tutor answer on this lesson.'
)
COMMENT 'How each lesson is going, over all time: one row per lesson in the running course, including lessons nobody has opened. Counts add up across lessons; the rate columns are per lesson, so to combine lessons add the counts and divide. Read every rate with its count.'
AS
WITH ll AS (
  SELECT
    x.lesson_id,
    COUNT(*) AS learners_opened,
    COUNT_IF(x.furthest_step_number >= 1) AS learners_past_learn,
    COUNT_IF(x.furthest_step_number >= 2) AS learners_reached_build,
    COUNT_IF(x.furthest_step_number >= 3) AS learners_reached_explain,
    COUNT_IF(x.is_finished) AS learners_finished,
    COUNT_IF(x.furthest_step_number >= 1 AND NOT x.is_finished AND NOT x.is_stalled) AS learners_in_progress,
    COUNT_IF(x.is_stalled) AS learners_stalled,
    COUNT_IF(x.is_stuck) AS learners_stuck,
    COUNT_IF(x.left_unfinished_after_struggling) AS learners_left_after_struggling,
    COUNT_IF(x.first_check_answer_right IS NOT NULL) AS first_check_answers,
    COUNT_IF(x.first_check_answer_right = false) AS first_check_wrong,
    SUM(x.check_questions_tried) AS check_questions_tried,
    SUM(x.check_questions_on_own) AS check_questions_on_own,
    SUM(x.check_answers_shown) AS check_answers_shown,
    COUNT_IF(x.practice_questions IS NOT NULL) AS practice_learners,
    SUM(x.practice_questions) AS practice_questions,
    SUM(x.practice_right_first_time) AS practice_right_first_time,
    COUNT_IF(x.exercise_solved_how = 'Code') AS code_solvers,
    COUNT_IF(x.exercise_solved_how = 'Code' AND x.code_hint_level >= 2) AS code_solvers_two_plus_hints,
    COUNT_IF(x.explain_gaps_done) AS explain_completions,
    SUM(CASE WHEN x.explain_gaps_done THEN x.explain_wrong_picks END) AS explain_wrong_picks,
    SUM(x.tutor_requests) AS tutor_requests,
    SUM(x.typed_questions) AS typed_questions,
    SUM(x.still_stuck_presses) AS still_stuck_presses
  FROM `{insights_catalog}`.drill_insights.learner_lessons x
  GROUP BY x.lesson_id
)
SELECT
  l.lesson_id,
  l.lesson,
  l.lesson_number,
  l.phase,
  l.phase_order,
  l.module,
  l.course_part,
  l.`position`,
  coalesce(ll.learners_opened, 0) AS learners_opened,
  coalesce(ll.learners_past_learn, 0) AS learners_past_learn,
  coalesce(ll.learners_reached_build, 0) AS learners_reached_build,
  coalesce(ll.learners_reached_explain, 0) AS learners_reached_explain,
  coalesce(ll.learners_finished, 0) AS learners_finished,
  coalesce(ll.learners_in_progress, 0) AS learners_in_progress,
  coalesce(ll.learners_stalled, 0) AS learners_stalled,
  coalesce(ll.learners_stuck, 0) AS learners_stuck,
  coalesce(ll.learners_left_after_struggling, 0) AS learners_left_after_struggling,
  -- Settled learners only: finished / (finished + stalled). People working on it now do not count against it.
  try_divide(ll.learners_finished, ll.learners_finished + ll.learners_stalled) AS finish_rate,
  coalesce(ll.first_check_answers, 0) AS first_check_answers,
  coalesce(ll.first_check_wrong, 0) AS first_check_wrong,
  try_divide(ll.first_check_wrong, ll.first_check_answers) AS first_check_wrong_rate,
  coalesce(ll.check_questions_tried, 0) AS check_questions_tried,
  coalesce(ll.check_questions_on_own, 0) AS check_questions_on_own,
  coalesce(ll.check_answers_shown, 0) AS check_answers_shown,
  try_divide(ll.check_questions_on_own, ll.check_questions_tried) AS check_on_own_rate,
  coalesce(ll.practice_learners, 0) AS practice_learners,
  try_divide(ll.practice_right_first_time, ll.practice_questions) AS practice_right_rate,
  coalesce(ll.code_solvers, 0) AS code_solvers,
  try_divide(ll.code_solvers_two_plus_hints, ll.code_solvers) AS code_two_plus_hints_rate,
  coalesce(ll.explain_completions, 0) AS explain_completions,
  try_divide(ll.explain_wrong_picks, ll.explain_completions) AS explain_wrong_picks_per_learner,
  coalesce(ll.tutor_requests, 0) AS tutor_requests,
  coalesce(ll.typed_questions, 0) AS typed_questions,
  coalesce(ll.still_stuck_presses, 0) AS still_stuck_presses
FROM `{insights_catalog}`.drill_insights.lessons l
LEFT JOIN ll ON ll.lesson_id = l.lesson_id
